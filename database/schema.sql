-- ---------- 1. SATELLITE ---------------------------------------------
CREATE TABLE satellite (
  satellite_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 10000),
  satellite_name  VARCHAR2(60)  NOT NULL,
  operator_name   VARCHAR2(60)  NOT NULL,
  launch_date     DATE          NOT NULL,
  orbit_type      VARCHAR2(20)  NOT NULL,
  sat_status      VARCHAR2(15)  DEFAULT 'ACTIVE' NOT NULL,
  revisit_days    NUMBER(3),
  CONSTRAINT pk_satellite PRIMARY KEY (satellite_id),
  CONSTRAINT uq_satellite_name UNIQUE (satellite_name),
  CONSTRAINT ck_sat_orbit  CHECK (orbit_type IN ('SUN-SYNCHRONOUS','GEOSTATIONARY','POLAR','OTHER')),
  CONSTRAINT ck_sat_status CHECK (sat_status IN ('ACTIVE','DECOMMISSIONED')),
  CONSTRAINT ck_sat_revisit CHECK (revisit_days > 0)
);

-- ---------- 2. SENSOR (instrument carried by a satellite) -------------
CREATE TABLE sensor (
  sensor_id             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 10000),
  satellite_id          NUMBER        NOT NULL,
  sensor_name           VARCHAR2(40)  NOT NULL,
  sensor_type           VARCHAR2(10)  NOT NULL,
  spatial_resolution_m  NUMBER(6,1)   NOT NULL,
  num_bands             NUMBER(3)     NOT NULL,
  CONSTRAINT pk_sensor PRIMARY KEY (sensor_id),
  CONSTRAINT fk_sensor_sat FOREIGN KEY (satellite_id) REFERENCES satellite(satellite_id) ON DELETE CASCADE,
  CONSTRAINT uq_sensor UNIQUE (satellite_id, sensor_name),
  CONSTRAINT ck_sensor_type CHECK (sensor_type IN ('OPTICAL','SAR','THERMAL')),
  CONSTRAINT ck_sensor_res  CHECK (spatial_resolution_m > 0),
  CONSTRAINT ck_sensor_band CHECK (num_bands > 0)
);

-- ---------- 3. RIVER_BASIN -------------------------------------------
CREATE TABLE river_basin (
  basin_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 10000),
  basin_name     VARCHAR2(80)  NOT NULL,
  basin_code     VARCHAR2(10)  NOT NULL,
  river_ref_lat  NUMBER(8,5)   NOT NULL,   -- reference point on the main river
  river_ref_lon  NUMBER(8,5)   NOT NULL,
  area_sq_km     NUMBER(12)    NOT NULL,
  basin_description VARCHAR2(300),
  CONSTRAINT pk_river_basin PRIMARY KEY (basin_id),
  CONSTRAINT uq_basin_code UNIQUE (basin_code),
  CONSTRAINT uq_basin_name UNIQUE (basin_name),
  CONSTRAINT ck_basin_lat CHECK (river_ref_lat BETWEEN -90 AND 90),
  CONSTRAINT ck_basin_lon CHECK (river_ref_lon BETWEEN -180 AND 180),
  CONSTRAINT ck_basin_area CHECK (area_sq_km > 0)
);

-- ---------- 4. LOCATION ----------------------------------------------
CREATE TABLE location (
  location_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 10000),
  basin_id       NUMBER,                    -- nullable: not every place lies in a basin
  location_name  VARCHAR2(80)  NOT NULL,
  country        VARCHAR2(60)  NOT NULL,
  latitude       NUMBER(8,5)   NOT NULL,
  longitude      NUMBER(8,5)   NOT NULL,
  region_type    VARCHAR2(20)  NOT NULL,
  CONSTRAINT pk_location PRIMARY KEY (location_id),
  CONSTRAINT fk_loc_basin FOREIGN KEY (basin_id) REFERENCES river_basin(basin_id) ON DELETE SET NULL,
  CONSTRAINT uq_location_name UNIQUE (location_name),
  CONSTRAINT ck_loc_lat CHECK (latitude BETWEEN -90 AND 90),
  CONSTRAINT ck_loc_lon CHECK (longitude BETWEEN -180 AND 180),
  CONSTRAINT ck_loc_region CHECK (region_type IN
    ('FOREST','WETLAND','URBAN','PORT','COASTAL','AGRICULTURE','FLOODPLAIN'))
);

-- ---------- 5. IMAGE_FRAME -------------------------------------------
-- satellite is reached through sensor (sensor -> satellite); resolution lives in SENSOR.
-- This avoids transitive dependencies (BCNF).
CREATE TABLE image_frame (
  image_id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 10000),
  sensor_id        NUMBER        NOT NULL,
  location_id      NUMBER        NOT NULL,
  capture_time     TIMESTAMP     NOT NULL,
  cloud_cover      NUMBER(5,2)   NOT NULL,
  sun_elevation    NUMBER(5,2),
  file_path        VARCHAR2(250) NOT NULL,
  image_embedding  CLOB,                       -- JSON array (8-dim demo; 512-dim in production)
  image_created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_image_frame PRIMARY KEY (image_id),
  CONSTRAINT fk_img_sensor FOREIGN KEY (sensor_id)   REFERENCES sensor(sensor_id),
  CONSTRAINT fk_img_loc    FOREIGN KEY (location_id) REFERENCES location(location_id),
  CONSTRAINT uq_img_capture UNIQUE (sensor_id, location_id, capture_time),
  CONSTRAINT uq_img_path    UNIQUE (file_path),
  CONSTRAINT ck_img_cloud CHECK (cloud_cover BETWEEN 0 AND 100),
  CONSTRAINT ck_img_sun   CHECK (sun_elevation BETWEEN 0 AND 90),
  CONSTRAINT ck_img_emb   CHECK (image_embedding IS JSON)
);

-- ---------- 6. OBJECT_TYPE -------------------------------------------
CREATE TABLE object_type (
  object_type_id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 10000),
  type_name               VARCHAR2(40)  NOT NULL,
  category                VARCHAR2(30)  NOT NULL,
  object_type_description VARCHAR2(200),
  CONSTRAINT pk_object_type PRIMARY KEY (object_type_id),
  CONSTRAINT uq_type_name UNIQUE (type_name)
);

-- ---------- 7. DETECTION_MODEL ---------------------------------------
CREATE TABLE detection_model (
  model_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 10000),
  model_name     VARCHAR2(50) NOT NULL,
  model_version  VARCHAR2(15) NOT NULL,
  architecture   VARCHAR2(50) NOT NULL,
  trained_on     VARCHAR2(100),
  released_date  DATE,
  CONSTRAINT pk_detection_model PRIMARY KEY (model_id),
  CONSTRAINT uq_model UNIQUE (model_name, model_version)
);

-- ---------- 8. DETECTED_OBJECT ---------------------------------------
-- basin is NOT stored here: object -> image -> location -> basin (avoids redundancy)
CREATE TABLE detected_object (
  object_id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 10000),
  image_id          NUMBER       NOT NULL,
  object_type_id    NUMBER       NOT NULL,
  model_id          NUMBER       NOT NULL,
  confidence_score  NUMBER(4,3)  NOT NULL,
  bbox_min_lat      NUMBER(8,5)  NOT NULL,
  bbox_min_lon      NUMBER(8,5)  NOT NULL,
  bbox_max_lat      NUMBER(8,5)  NOT NULL,
  bbox_max_lon      NUMBER(8,5)  NOT NULL,
  area_sq_m         NUMBER(14,2) NOT NULL,
  object_embedding  CLOB,
  attributes_json   CLOB,
  object_created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_detected_object PRIMARY KEY (object_id),
  CONSTRAINT fk_obj_image FOREIGN KEY (image_id)       REFERENCES image_frame(image_id) ON DELETE CASCADE,
  CONSTRAINT fk_obj_type  FOREIGN KEY (object_type_id) REFERENCES object_type(object_type_id),
  CONSTRAINT fk_obj_model FOREIGN KEY (model_id)       REFERENCES detection_model(model_id),
  CONSTRAINT ck_obj_conf  CHECK (confidence_score BETWEEN 0 AND 1),
  CONSTRAINT ck_obj_area  CHECK (area_sq_m > 0),
  CONSTRAINT ck_obj_bbox  CHECK (bbox_min_lat < bbox_max_lat AND bbox_min_lon < bbox_max_lon),
  CONSTRAINT ck_obj_emb   CHECK (object_embedding IS JSON),
  CONSTRAINT ck_obj_attr  CHECK (attributes_json IS JSON)
);

-- ---------- 9. OBJECT_CHANGE  (EVOLVED_FROM : the temporal-lineage novelty) ----
CREATE TABLE object_change (
  change_id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 10000),
  prev_object_id     NUMBER       NOT NULL,
  curr_object_id     NUMBER       NOT NULL,
  change_type        VARCHAR2(20) NOT NULL,
  change_pct         NUMBER(8,2)  NOT NULL,   -- +ve = area lost, -ve = area gained
  time_delta_days    NUMBER(5)    NOT NULL,
  rate_pct_per_month NUMBER(8,2)  NOT NULL,
  computed_at        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_object_change PRIMARY KEY (change_id),
  CONSTRAINT fk_chg_prev FOREIGN KEY (prev_object_id) REFERENCES detected_object(object_id) ON DELETE CASCADE,
  CONSTRAINT fk_chg_curr FOREIGN KEY (curr_object_id) REFERENCES detected_object(object_id) ON DELETE CASCADE,
  CONSTRAINT uq_chg_pair UNIQUE (prev_object_id, curr_object_id),
  CONSTRAINT ck_chg_diff CHECK (prev_object_id <> curr_object_id),
  CONSTRAINT ck_chg_type CHECK (change_type IN ('DEFORESTATION','GRADUAL_LOSS','STABLE','REGROWTH')),
  CONSTRAINT ck_chg_days CHECK (time_delta_days > 0)
);

-- ---------- 10. SPECTRAL_INDEX ---------------------------------------
CREATE TABLE spectral_index (
  index_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 10000),
  image_id    NUMBER       NOT NULL,
  index_name  VARCHAR2(10) NOT NULL,
  mean_value  NUMBER(6,4)  NOT NULL,
  min_value   NUMBER(6,4)  NOT NULL,
  max_value   NUMBER(6,4)  NOT NULL,
  CONSTRAINT pk_spectral_index PRIMARY KEY (index_id),
  CONSTRAINT fk_si_image FOREIGN KEY (image_id) REFERENCES image_frame(image_id) ON DELETE CASCADE,
  CONSTRAINT uq_si UNIQUE (image_id, index_name),
  CONSTRAINT ck_si_name  CHECK (index_name IN ('NDVI','NDWI','NBR')),
  CONSTRAINT ck_si_range CHECK (min_value <= mean_value AND mean_value <= max_value
                                AND min_value >= -1 AND max_value <= 1)
);

-- ---------- 11. APP_USER ---------------------------------------------
CREATE TABLE app_user (
  user_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 10000),
  full_name   VARCHAR2(80)  NOT NULL,
  email       VARCHAR2(120) NOT NULL,
  user_role   VARCHAR2(10)  NOT NULL,
  user_created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_app_user PRIMARY KEY (user_id),
  CONSTRAINT uq_user_email UNIQUE (email),
  CONSTRAINT ck_user_role CHECK (user_role IN ('ANALYST','ADMIN','VIEWER')),
  CONSTRAINT ck_user_email CHECK (email LIKE '%_@_%._%')
);

-- ---------- 12. QUERY_LOG  (GraphRAG question asked by a user) -------
CREATE TABLE query_log (
  query_id               NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 10000),
  user_id                NUMBER,
  query_text             VARCHAR2(500) NOT NULL,
  query_embedding        CLOB,
  submitted_at           TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  response_text          VARCHAR2(1000),
  retrieval_weights_json CLOB NOT NULL,        -- {"alpha":..,"beta":..,"gamma":..}
  aggregated_confidence  NUMBER(5,4),          -- derived by pkg_eo.fn_query_confidence
  CONSTRAINT pk_query_log PRIMARY KEY (query_id),
  CONSTRAINT fk_q_user FOREIGN KEY (user_id) REFERENCES app_user(user_id) ON DELETE SET NULL,
  CONSTRAINT ck_q_conf CHECK (aggregated_confidence BETWEEN 0 AND 1),
  CONSTRAINT ck_q_w    CHECK (retrieval_weights_json IS JSON),
  CONSTRAINT ck_q_emb  CHECK (query_embedding IS JSON)
);

-- ---------- 13. QUERY_EVIDENCE  (associative entity: QUERY_LOG M:N DETECTED_OBJECT) ----
CREATE TABLE query_evidence (
  evidence_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 10000),
  query_id        NUMBER      NOT NULL,
  object_id       NUMBER      NOT NULL,
  semantic_score  NUMBER(5,4) NOT NULL,
  spatial_score   NUMBER(5,4) NOT NULL,
  temporal_score  NUMBER(5,4) NOT NULL,
  retrieval_score NUMBER(5,4) NOT NULL,
  rank_position   NUMBER(3)   NOT NULL,
  CONSTRAINT pk_query_evidence PRIMARY KEY (evidence_id),
  CONSTRAINT fk_qe_query  FOREIGN KEY (query_id)  REFERENCES query_log(query_id) ON DELETE CASCADE,
  CONSTRAINT fk_qe_object FOREIGN KEY (object_id) REFERENCES detected_object(object_id) ON DELETE CASCADE,
  CONSTRAINT uq_qe UNIQUE (query_id, object_id),
  CONSTRAINT ck_qe_scores CHECK (semantic_score BETWEEN 0 AND 1 AND spatial_score BETWEEN 0 AND 1
                                 AND temporal_score BETWEEN 0 AND 1 AND retrieval_score BETWEEN 0 AND 1),
  CONSTRAINT ck_qe_rank CHECK (rank_position > 0)
);

-- ---------- 14. ALERT  (raised from significant changes) -------------
CREATE TABLE alert (
  alert_id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 10000),
  change_id        NUMBER       NOT NULL,
  assigned_user_id NUMBER,
  severity         VARCHAR2(10) NOT NULL,
  alert_status     VARCHAR2(10) DEFAULT 'OPEN' NOT NULL,
  raised_at        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  resolved_at      TIMESTAMP,
  CONSTRAINT pk_alert PRIMARY KEY (alert_id),
  CONSTRAINT fk_alert_chg  FOREIGN KEY (change_id) REFERENCES object_change(change_id) ON DELETE CASCADE,
  CONSTRAINT fk_alert_user FOREIGN KEY (assigned_user_id) REFERENCES app_user(user_id) ON DELETE SET NULL,
  CONSTRAINT uq_alert_change UNIQUE (change_id),
  CONSTRAINT ck_alert_sev CHECK (severity IN ('MEDIUM','HIGH','CRITICAL')),
  CONSTRAINT ck_alert_st  CHECK (alert_status IN ('OPEN','REVIEWING','RESOLVED')),
  CONSTRAINT ck_alert_res CHECK (resolved_at IS NULL OR alert_status = 'RESOLVED')
);

-- ---------- 15. AUDIT_LOG  (filled automatically by triggers) --------
CREATE TABLE audit_log (
  audit_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1),
  table_name  VARCHAR2(30)   NOT NULL,
  operation   VARCHAR2(10)   NOT NULL,
  record_id   NUMBER,
  changed_by  VARCHAR2(60)   DEFAULT USER NOT NULL,
  changed_at  TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  old_value   VARCHAR2(500),
  new_value   VARCHAR2(500),
  CONSTRAINT pk_audit_log PRIMARY KEY (audit_id),
  CONSTRAINT ck_audit_op CHECK (operation IN ('INSERT','UPDATE','DELETE'))
);


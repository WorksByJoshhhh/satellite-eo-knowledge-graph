BEGIN
  FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN
    ('AUDIT_LOG','ALERT','QUERY_EVIDENCE','QUERY_LOG','APP_USER','OBJECT_CHANGE',
     'SPECTRAL_INDEX','DETECTED_OBJECT','DETECTION_MODEL','OBJECT_TYPE','IMAGE_FRAME',
     'LOCATION','RIVER_BASIN','SENSOR','SATELLITE')) LOOP
    EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
  END LOOP;
END;

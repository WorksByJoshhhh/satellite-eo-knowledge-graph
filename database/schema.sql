-- ---------- views -----------------------------------------------------
CREATE OR REPLACE VIEW v_image_summary AS
SELECT i.image_id, i.capture_time, i.cloud_cover,
       s.satellite_name, sn.sensor_name, sn.spatial_resolution_m,
       l.location_name, l.country, b.basin_name
FROM image_frame i
JOIN sensor sn    ON sn.sensor_id = i.sensor_id
JOIN satellite s  ON s.satellite_id = sn.satellite_id
JOIN location l   ON l.location_id = i.location_id
LEFT JOIN river_basin b ON b.basin_id = l.basin_id;

CREATE OR REPLACE VIEW v_forest_change AS
SELECT oc.change_id, l.location_id, l.location_name, b.basin_name,
       i2.capture_time AS curr_time, oc.change_type, oc.change_pct,
       oc.time_delta_days, oc.rate_pct_per_month,
       o1.confidence_score AS prev_conf, o2.confidence_score AS curr_conf,
       i1.cloud_cover AS prev_cloud, i2.cloud_cover AS curr_cloud
FROM object_change oc
JOIN detected_object o1 ON o1.object_id = oc.prev_object_id
JOIN detected_object o2 ON o2.object_id = oc.curr_object_id
JOIN image_frame i1 ON i1.image_id = o1.image_id
JOIN image_frame i2 ON i2.image_id = o2.image_id
JOIN location l ON l.location_id = i2.location_id
LEFT JOIN river_basin b ON b.basin_id = l.basin_id;
